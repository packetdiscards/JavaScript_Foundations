/*
Example of javaScript array operations similar to Python list operations.
*/

// Creating an array
const myList = ['apple', 'banana', 'cherry'];
console.log('Original array:', myList); 

// Array length
console.log('Length of array:', myList.length);

// Accessing elements
console.log('First element:', myList[1]);
console.log('Last element:', myList[myList.length - 1]);

// Adding elements
myList.push('orange');
console.log('After push:', myList);