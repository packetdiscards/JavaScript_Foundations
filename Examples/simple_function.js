/*
Example JavaScript function that adds two numbers.
*/

// Function to add two numbers
function addNumbers(a, b) {
    return a + b;
}

// Example usage
const num1 = 5;
const num2 = 10;
const sum = addNumbers(num1, num2);

// Print the result
console.log(`The sum of ${num1} and ${num2} is: ${sum}`);

// Run file in terminal using node simple_function.js 
console.log('Simple function example completed.');
